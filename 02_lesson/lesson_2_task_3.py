
# Напишите функцию square, принимающую один аргумент
# — сторону квадрата — и возвращающую площадь квадрата.
# Если переданный аргумент был не целым, округлите результат вверх.

import math


def square(x):
    return math.ceil(x*x)


# Считываем сторону как число с плавающей точкой (включая дробные)
square_side = float(input("Введите сторону квадрата: "))

# Вызываем функцию и выводим результат
result = square(square_side)
print(result)
